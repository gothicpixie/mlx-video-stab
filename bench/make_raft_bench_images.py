"""Write the deterministic image pair used by bench/bench_raft.py.

``bench/bench_raft.py`` constructs its timing inputs with::

    rng = np.random.default_rng(0)
    a = (rng.random((H, W, 3)) * 255).astype(np.float32)
    b = np.roll(a, (3, -5), (0, 1))

This tool reproduces that construction exactly and writes two raw interleaved
float32 images (NHWC, row-major, little-endian) plus a manifest containing
shapes, byte counts and SHA-256 digests. The Rust ``bench_flow_bidir`` example
reads these files so the Rust/MLX, Python MLX and PyTorch MPS runs share one
byte-identical input pair.

This is benchmark input preparation only. It does not import MLX, run RAFT or
produce a timing or quality measurement.

Run from the repository root::

    .venv/bin/python -I bench/make_raft_bench_images.py \
        --height 256 --width 320 --out-dir out/raft-bench/pair-256x320
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

SEED = 0
ROLL_YX = (3, -5)
CHANNELS = 3


def frame_pair(height: int, width: int) -> tuple[np.ndarray, np.ndarray]:
    """Return the exact pair generated by ``bench/bench_raft.py`` for this H/W."""
    rng = np.random.default_rng(SEED)
    first = (rng.random((height, width, CHANNELS)) * 255).astype(np.float32)
    second = np.roll(first, ROLL_YX, (0, 1))
    return first, second


def write_raw(path: Path, image: np.ndarray) -> dict:
    """Write one NHWC interleaved little-endian float32 image and describe it."""
    payload = np.ascontiguousarray(image, dtype="<f4").tobytes()
    path.write_bytes(payload)
    return {
        "path": path.name,
        "shape": list(image.shape),
        "layout": "NHWC interleaved, row-major",
        "dtype": "float32",
        "byte_order": "little",
        "bytes": len(payload),
        "sha256": hashlib.sha256(payload).hexdigest(),
    }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--height", type=int, default=256, help="frame height (default: 256)")
    parser.add_argument("--width", type=int, default=320, help="frame width (default: 320)")
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("out/raft-bench/pair-256x320"),
        help="directory for first.f32, second.f32 and pair.json (default: %(default)s)",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if args.height <= 0 or args.width <= 0:
        raise SystemExit("height and width must be positive")
    if args.height % 8 or args.width % 8:
        # The Rust compatibility API requires H and W to be multiples of 8.
        # bench_raft.py itself does not pad, so keep the shared pair valid for
        # every backend in the matched harness.
        raise SystemExit("height and width must be multiples of 8")

    first, second = frame_pair(args.height, args.width)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    manifest = {
        "schema": "mlxstab.raft_bench.pair/1",
        "generator": "bench/make_raft_bench_images.py",
        "source": "exact reproduction of the deterministic pair in bench/bench_raft.py",
        "rng": "numpy.random.default_rng",
        "rng_algorithm": "PCG64",
        "seed": SEED,
        "height": args.height,
        "width": args.width,
        "channels": CHANNELS,
        "roll_yx": list(ROLL_YX),
        "images": {
            "first": write_raw(args.out_dir / "first.f32", first),
            "second": write_raw(args.out_dir / "second.f32", second),
        },
        "notes": (
            "Raw files contain float32 pixel values in 0..255, not uint8. "
            "The second image is np.roll(first, (3, -5), axis=(0, 1))."
        ),
    }
    manifest_path = args.out_dir / "pair.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {args.out_dir / 'first.f32'}")
    print(f"wrote {args.out_dir / 'second.f32'}")
    print(f"wrote {manifest_path}")


if __name__ == "__main__":
    main()
